#!/usr/bin/env node
/**
 * keystone token builder — zero dependencies.
 *
 *   node build.mjs --theme design/theme.json --out src/styles/tokens.css
 *
 * Deep-merges the project theme over the neutral defaults and emits CSS custom
 * properties. The output file is generated: never edit it by hand.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};

const themePath = arg("--theme", null);
const outPath = arg("--out", "tokens.css");
const defaults = JSON.parse(readFileSync(resolve(here, "tokens.json"), "utf8"));

const isObj = (v) => v && typeof v === "object" && !Array.isArray(v);
const merge = (base, over) => {
  if (!isObj(base) || !isObj(over)) return over ?? base;
  const out = { ...base };
  for (const [k, v] of Object.entries(over)) out[k] = merge(base[k], v);
  return out;
};

const theme = themePath ? JSON.parse(readFileSync(resolve(process.cwd(), themePath), "utf8")) : {};
const merged = merge(defaults, theme);

const lines = [
  "/* GENERATED by @keystone/tokens — do not edit. Source: design/theme.json */",
  ":root {",
];
for (const [group, values] of Object.entries(merged)) {
  if (group.startsWith("$") || !isObj(values)) continue;
  lines.push(`  /* ${group} */`);
  for (const [key, value] of Object.entries(values)) {
    lines.push(`  --${group}-${key}: ${value};`);
  }
}
lines.push("}", "");

const target = resolve(process.cwd(), outPath);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, lines.join("\n"));
console.log(`wrote ${outPath} (${Object.keys(merged).length} groups)`);
